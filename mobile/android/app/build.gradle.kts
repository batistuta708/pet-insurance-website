            // Uses your upload key when android/key.properties exists; otherwise falls back to
            // the debug key so `flutter run --release` still works (Google Play rejects that build).
            signingConfig = if (keystorePropertiesFile.exists()) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }
